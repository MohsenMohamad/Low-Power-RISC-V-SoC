#!/usr/bin/env python3
"""Build a single-file bundle of the PMU UVM environment for EDA Playground.

Reads scripts/pmu_uvm.f, inlines every local `include (the agent/env .svh
files and pwr_defines.svh), keeps `include "uvm_macros.svh" (provided by the
simulator's UVM library) and writes bundle/pmu_uvm_edaplayground.sv.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
FLIST = os.path.join(HERE, "pmu_uvm.f")
OUT = os.path.join(ROOT, "bundle", "pmu_uvm_edaplayground.sv")

INC_RE = re.compile(r'^\s*`include\s+"([^"]+)"')

HEADER = """\
// =============================================================================
// PMU UVM environment - single-file bundle for EDA Playground
// Generated by verif/uvm/scripts/mk_bundle.py from verif/uvm/ - do not edit.
//
// EDA Playground setup:
//   * Testbench + Design: SystemVerilog/Verilog
//   * UVM / OVM: UVM 1.2 (or IEEE 1800.2 where offered)
//   * Tools & Simulators: Cadence Xcelium, Siemens Questa or Synopsys VCS
//   * Paste this whole file into testbench.sv; design.sv may stay empty
//     (the stub PMU is included below).
//   * Top module: pmu_tb_top
//   * Run options: +UVM_TESTNAME=pmu_smoke_test   (or any test below)
//       seed: Xcelium -svseed <n>, Questa -sv_seed <n>, VCS +ntb_random_seed=<n>
//   * Tests: pmu_smoke_test pmu_ral_test pmu_rand_reg_test pmu_rand_pwr_test
//            pmu_pwr_matrix_test pmu_err_test pmu_full_test
// =============================================================================
`timescale 1ns/1ps
"""


def read_flist(path):
    incdirs, files = [], []
    base = os.path.dirname(path)
    for line in open(path):
        line = line.split("//")[0].strip()
        if not line:
            continue
        if line.startswith("+incdir+"):
            incdirs.append(os.path.normpath(os.path.join(base, line[len("+incdir+"):])))
        else:
            files.append(os.path.normpath(os.path.join(base, line)))
    return incdirs, files


def find_inc(name, cur_dir, incdirs):
    for d in [cur_dir] + incdirs:
        p = os.path.join(d, name)
        if os.path.isfile(p):
            return p
    return None


def expand(path, incdirs, seen, out):
    rel = os.path.relpath(path, ROOT)
    out.append(f"\n// ---- begin {rel} ----\n")
    for line in open(path):
        m = INC_RE.match(line)
        if m:
            inc = find_inc(m.group(1), os.path.dirname(path), incdirs)
            if inc is None:          # uvm_macros.svh etc.: from the simulator
                out.append(line)
                continue
            if inc in seen and os.path.basename(inc) == "pwr_defines.svh":
                continue             # header-guarded, include once
            seen.add(inc)
            expand(inc, incdirs, seen, out)
            continue
        if line.startswith("`timescale"):
            continue
        out.append(line)
    out.append(f"// ---- end {rel} ----\n")


def main():
    incdirs, files = read_flist(FLIST)
    out = [HEADER]
    seen = set()
    for f in files:
        expand(f, incdirs, seen, out)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write("".join(out))
    print(f"wrote {os.path.relpath(OUT, os.getcwd())} ({sum(s.count(chr(10)) for s in out)} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
